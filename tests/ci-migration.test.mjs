import assert from 'node:assert/strict';
import {migrationSettings,mayChangeLock,targetIsEmpty,sameSnapshot} from '../migration/ci-migration-guards.mjs';
const config={name:'goalforge-football',main:'cloudflare/migration-worker.ts',vars:{MIGRATION_MODE:'import'},durable_objects:{bindings:[{name:'ARENA',class_name:'ArenaRecords'}]}};
const env={NETLIFY_AUTH_TOKEN:'test-netlify',CLOUDFLARE_API_TOKEN:'test-cf',CLOUDFLARE_ACCOUNT_ID:'a'.repeat(32)};
assert.equal(migrationSettings(env,config).account_id,env.CLOUDFLARE_ACCOUNT_ID);
assert.deepEqual(config.vars,{MIGRATION_MODE:'import'});
assert.throws(()=>migrationSettings({...env,NETLIFY_AUTH_TOKEN:''},config));
assert.throws(()=>migrationSettings({...env,CLOUDFLARE_API_TOKEN:''},config));
assert.throws(()=>migrationSettings({...env,CLOUDFLARE_ACCOUNT_ID:'wrong'},config));
assert.throws(()=>migrationSettings({...env,CLOUDFLARE_LIVE_READY:'true'},config));
assert.throws(()=>migrationSettings(env,{...config,vars:{MIGRATION_MODE:'live'}}));
mayChangeLock({active:false},'freeze','gha-1');
mayChangeLock({active:true,owner:'gha-1'},'unfreeze','gha-1');
assert.throws(()=>mayChangeLock({active:true,owner:'gha-2'},'unfreeze','gha-1'),'never unlock a different migration');
assert.throws(()=>mayChangeLock({active:true,owner:'gha-2'},'freeze','gha-1'));
mayChangeLock({active:true},'unfreeze','local');
assert.throws(()=>mayChangeLock({active:true},'unfreeze','gha-1'));
assert(targetIsEmpty({rooms:[],records:[]}));
assert(targetIsEmpty({rooms:[],records:[{id:'__migration_probe'}]}));
assert(!targetIsEmpty({rooms:[],records:[{id:'__password_admin'}]}),'orphaned account records are not an empty target');
assert(!targetIsEmpty({rooms:['room'],records:[]}));
assert(!targetIsEmpty({}));
assert(sameSnapshot({hash:'same',records:[{id:'__password_admin'}]},{hash:'same'}));
assert(!sameSnapshot({hash:'same',records:[]},{hash:'same'}));
assert(!sameSnapshot({hash:'old',records:[{id:'__password_admin'}]},{hash:'new'}));
console.log('CI migration guards passed: exact target, credentials, lock ownership, empty target and stable full-account snapshots.');
